import json
import numpy as np
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional

from db.models.assessment import StressAssessment


class LongitudinalAnalyticsService:
    """
    Authoritative backend service for longitudinal welfare analytics (Phase 36).
    Consumes historical assessment results generated by Welfare Risk Engine V2.
    Provides administrative welfare-monitoring trend intelligence without punitive or causal framing.
    """

    @staticmethod
    def calculate_longitudinal_trend(
        personnel_id: int,
        assessments: List[StressAssessment],
        reference_time: Optional[datetime] = None
    ) -> Dict[str, Any]:
        """
        Calculates longitudinal trend intelligence from a person's assessment history.
        Assumes assessments are pre-fetched from DB for this personnel.
        """
        if not assessments:
            return LongitudinalAnalyticsService._empty_response(personnel_id)

        # 1. History Data Quality & Sorting (Step 15)
        # Filter valid records, handle missing/duplicate timestamps, sort chronologically.
        valid_assessments = []
        for a in assessments:
            # Safely handle null/NaN scores
            if a.risk_score is None:
                continue
            try:
                score = float(a.risk_score)
                if np.isnan(score) or np.isinf(score):
                    continue
            except (ValueError, TypeError):
                continue
            
            # Default timestamp to epoch if missing
            ts = a.assessment_timestamp
            if ts is None:
                ts = datetime.min.replace(tzinfo=timezone.utc)
            elif ts.tzinfo is None:
                ts = ts.replace(tzinfo=timezone.utc)
            
            # Extract key factors safely
            key_factors = []
            if a.key_factors:
                try:
                    parsed = json.loads(a.key_factors)
                    if isinstance(parsed, list):
                        key_factors = parsed
                    elif isinstance(parsed, dict):
                        key_factors = parsed.get("top_risk_factors", parsed.get("key_factors", []))
                    else:
                        key_factors = [str(parsed)]
                except Exception:
                    key_factors = [a.key_factors]
                    
            protective_factors = []
            if a.key_factors:
                try:
                    parsed = json.loads(a.key_factors)
                    if isinstance(parsed, dict):
                        protective_factors = parsed.get("protective_factors", [])
                except Exception:
                    pass

            valid_assessments.append({
                "id": a.id,
                "score": score,
                "category": a.stress_level, # or from risk_priority / meta
                "priority": a.risk_priority,
                "timestamp": ts,
                "key_factors": key_factors,
                "protective_factors": protective_factors
            })

        # Sort strictly chronologically (oldest to newest)
        # Using ID as a secondary stable sort key for duplicate timestamps
        valid_assessments.sort(key=lambda x: (x["timestamp"].timestamp(), x["id"]))

        if not valid_assessments:
            return LongitudinalAnalyticsService._empty_response(personnel_id)

        count = len(valid_assessments)
        current = valid_assessments[-1]
        previous = valid_assessments[-2] if count > 1 else None

        # 2. Data Sufficiency (Step 10)
        data_sufficiency = "INSUFFICIENT_DATA"
        if count == 2:
            data_sufficiency = "LIMITED_HISTORY"
        elif count >= 3:
            data_sufficiency = "SUFFICIENT_HISTORY"

        # 3. Current vs Historical Risk (Step 3)
        score_change = None
        if previous is not None:
            score_change = round(current["score"] - previous["score"], 1)

        # 4. Trend Classification (Step 4)
        # Threshold: > 4.0 points change is meaningful on the 100-point scale.
        trend_direction = "INSUFFICIENT_DATA"
        if score_change is not None:
            if score_change >= 5.0:
                trend_direction = "WORSENING"
            elif score_change <= -5.0:
                trend_direction = "IMPROVING"
            else:
                trend_direction = "STABLE"

        # 5. Trend Slope (Step 5)
        # Using simple linear regression slope over time (days since first assessment).
        trend_slope = None
        if data_sufficiency in ["LIMITED_HISTORY", "SUFFICIENT_HISTORY"]:
            earliest_ts = valid_assessments[0]["timestamp"].timestamp()
            x = np.array([(a["timestamp"].timestamp() - earliest_ts) / 86400.0 for a in valid_assessments]) # Days
            y = np.array([a["score"] for a in valid_assessments])
            
            # Handle identical timestamps (all x are same)
            if np.max(x) - np.min(x) > 0.01:
                slope, _ = np.polyfit(x, y, 1)
                trend_slope = round(float(slope), 3) # points per day
            else:
                # If they happen on the exact same day, fallback to sequence based
                x_seq = np.arange(count)
                slope, _ = np.polyfit(x_seq, y, 1)
                trend_slope = round(float(slope), 3) # points per assessment

        # 6. Persistent Elevated Risk (Step 6)
        # Check if recent assessments are consistently Elevated/High/Critical
        # V2 stress_level mapping: Critical/High -> "High", Elevated/Moderate -> "Medium", Low -> "Low"
        # We can map from priority: Priority = High/Critical, Preventive = Elevated/Moderate, Routine = Low
        persistent_elevated_risk = False
        consecutive_elevated = 0
        recent_average_score = None
        highest_recent_score = None

        if count > 0:
            highest_recent_score = current["score"]
            recent_scores = []
            for a in reversed(valid_assessments):
                recent_scores.append(a["score"])
                highest_recent_score = max(highest_recent_score, a["score"])
                # We consider score >= 55.0 as "Elevated" or higher (from V2 mapping).
                if a["score"] >= 55.0:
                    consecutive_elevated += 1
                else:
                    break
            
            # Determine persistence: 3 or more consecutive elevated assessments
            persistent_elevated_risk = consecutive_elevated >= 3
            
            # Recent average (up to last 5)
            last_5 = recent_scores[:5]
            recent_average_score = round(sum(last_5) / len(last_5), 1)

        # 7. Risk Acceleration (Step 7)
        # Compare slope of older half vs recent half if count >= 4
        trend_acceleration = "INSUFFICIENT_DATA"
        if count >= 4:
            mid = count // 2
            older_half = valid_assessments[:mid]
            recent_half = valid_assessments[mid:]
            
            older_y = [a["score"] for a in older_half]
            recent_y = [a["score"] for a in recent_half]
            
            older_x = np.arange(len(older_y))
            recent_x = np.arange(len(recent_y))
            
            older_slope, _ = np.polyfit(older_x, older_y, 1) if len(older_y) > 1 else (0, 0)
            recent_slope, _ = np.polyfit(recent_x, recent_y, 1) if len(recent_y) > 1 else (0, 0)
            
            slope_diff = recent_slope - older_slope
            
            # Meaningful acceleration threshold
            if slope_diff > 3.0:
                trend_acceleration = "INCREASING"
            elif slope_diff < -3.0:
                trend_acceleration = "DECREASING"
            else:
                trend_acceleration = "STABLE"

        # 8. Repeated Risk Factors (Step 8)
        repeated_factors = []
        if count > 1:
            factor_counts = {}
            factor_last_seen = {}
            for a in valid_assessments:
                for f in a["key_factors"]:
                    factor_counts[f] = factor_counts.get(f, 0) + 1
                    factor_last_seen[f] = a["timestamp"]
            
            for f, fcount in factor_counts.items():
                if fcount >= 2:
                    repeated_factors.append({
                        "factor": f,
                        "type": "risk",
                        "frequency": fcount,
                        "total_assessments": count,
                        "most_recent_occurrence": factor_last_seen[f].isoformat(),
                        "description": f"Present in {fcount} of {count} historical assessments."
                    })
            
            # Protective factors
            prot_factor_counts = {}
            prot_factor_last_seen = {}
            for a in valid_assessments:
                for p in a["protective_factors"]:
                    prot_factor_counts[p] = prot_factor_counts.get(p, 0) + 1
                    prot_factor_last_seen[p] = a["timestamp"]
            
            for p, pcount in prot_factor_counts.items():
                if pcount >= 2:
                    repeated_factors.append({
                        "factor": p,
                        "type": "protective",
                        "frequency": pcount,
                        "total_assessments": count,
                        "most_recent_occurrence": prot_factor_last_seen[p].isoformat(),
                        "description": f"Present in {pcount} of {count} historical assessments."
                    })
            
            repeated_factors.sort(key=lambda x: x["frequency"], reverse=True)

        # 9. Personal Baseline (Step 9)
        historical_mean = None
        historical_median = None
        historical_std = None
        current_deviation = None

        if count >= 3:
            # Exclude current for a true "historical" baseline, or include all? 
            # We'll use all history to establish a stable baseline.
            all_scores = [a["score"] for a in valid_assessments]
            historical_mean = round(float(np.mean(all_scores)), 1)
            historical_median = round(float(np.median(all_scores)), 1)
            historical_std = round(float(np.std(all_scores)), 1)
            current_deviation = round(current["score"] - historical_mean, 1)

        # Re-derive category from V2 scale since DB stores 'High/Medium/Low' string
        current_cat = LongitudinalAnalyticsService._get_v2_category(current["score"])

        return {
            "personnel_id": personnel_id,
            "current": {
                "risk_score": current["score"],
                "risk_category": current_cat,
                "assessment_timestamp": current["timestamp"].isoformat()
            },
            "trend": {
                "direction": trend_direction,
                "score_change": score_change,
                "slope": trend_slope,
                "acceleration": trend_acceleration
            },
            "history": {
                "assessment_count": count,
                "data_sufficiency": data_sufficiency,
                "persistent_elevated_risk": persistent_elevated_risk,
                "consecutive_elevated_assessments": consecutive_elevated,
                "recent_average_score": recent_average_score,
                "highest_recent_score": highest_recent_score
            },
            "baseline": {
                "historical_mean": historical_mean,
                "historical_median": historical_median,
                "historical_std": historical_std,
                "current_deviation": current_deviation
            },
            "repeated_factors": repeated_factors
        }

    @staticmethod
    def _get_v2_category(score: float) -> str:
        if score >= 85.0:
            return "Critical"
        elif score >= 70.0:
            return "High"
        elif score >= 55.0:
            return "Elevated"
        elif score >= 35.0:
            return "Moderate"
        else:
            return "Low"

    @staticmethod
    def _empty_response(personnel_id: int) -> Dict[str, Any]:
        return {
            "personnel_id": personnel_id,
            "current": None,
            "trend": {
                "direction": "INSUFFICIENT_DATA",
                "score_change": None,
                "slope": None,
                "acceleration": "INSUFFICIENT_DATA"
            },
            "history": {
                "assessment_count": 0,
                "data_sufficiency": "INSUFFICIENT_DATA",
                "persistent_elevated_risk": False,
                "consecutive_elevated_assessments": 0,
                "recent_average_score": None,
                "highest_recent_score": None
            },
            "baseline": {
                "historical_mean": None,
                "historical_median": None,
                "historical_std": None,
                "current_deviation": None
            },
            "repeated_factors": []
        }
