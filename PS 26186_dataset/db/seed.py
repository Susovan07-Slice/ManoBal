def seed_database():
    """Populates database with synthetic demo users, personnel, and assessments."""
    logger.info("Starting safe database seeding (SYNTHETIC DEMO DATA ONLY)...")
    from db.init_db import init_db
    init_db()
    db = SessionLocal()

    try:
        service = get_prediction_service()

        # 1. Seed Personnel Records
        created_personnel = []
        for p_data in DEMO_PERSONNEL_DATA:
            p_data_copy = dict(p_data)
            p_data_copy.setdefault("battalion", "7th Battalion")
            existing = db.query(Personnel).filter(Personnel.personnel_code == p_data_copy["personnel_code"]).first()
            if not existing:
                p = Personnel(**p_data_copy)
                db.add(p)
                db.flush()
                created_personnel.append(p)
                logger.info(f"Seeded synthetic personnel: {p.personnel_code} - {p.name}")
            else:
                existing.battalion = p_data_copy["battalion"]
                existing.location = p_data_copy["location"]
                created_personnel.append(existing)

        db.commit()

        # 2. Seed Role-Based Users with Organizational Scopes
        demo_users = [
            {
                "username": "admin",
                "password": "AdminPassword123!",
                "role": "admin",
                "personnel_id": None,
                "battalion": None,
                "location": None
            },
            {
                "username": "officer_sharma",
                "password": "OfficerPassword123!",
                "role": "officer",
                "personnel_id": None,
                "battalion": "7th Battalion",
                "location": "Srinagar"
            },
            {
                "username": "counselor_priya",
                "password": "WelfarePassword123!",
                "role": "welfare",
                "personnel_id": None,
                "battalion": "7th Battalion",
                "location": "Srinagar"
            },
            {
                "username": "jawan_verma",
                "password": "PersonnelPassword123!",
                "role": "personnel",
                "personnel_id": created_personnel[0].id if created_personnel else None,
                "battalion": "7th Battalion",
                "location": "Srinagar"
            }
        ]

        for u_data in demo_users:
            existing_u = db.query(User).filter(User.username == u_data["username"]).first()
            if not existing_u:
                user = User(
                    username=u_data["username"],
                    hashed_password=hash_password(u_data["password"]),
                    role=u_data["role"],
                    personnel_id=u_data["personnel_id"],
                    battalion=u_data["battalion"],
                    location=u_data["location"],
                    is_active=True
                )
                db.add(user)
                logger.info(f"Seeded demo user: '{u_data['username']}' with role '{u_data['role']}' ({u_data['battalion']} • {u_data['location']})")
            else:
                existing_u.battalion = u_data["battalion"]
                existing_u.location = u_data["location"]
                existing_u.hashed_password = hash_password(u_data["password"])

        db.commit()

        # 3. Seed Stress Assessments & Welfare Recommendations for Personnel
        for i, p in enumerate(created_personnel):
            # Check if personnel already has assessments
            existing_ass = db.query(StressAssessment).filter(StressAssessment.personnel_id == p.id).first()
            if not existing_ass:
                night_shifts = p.night_shifts_per_month
                consec_days = p.consecutive_duty_days
                leave_gap = p.leave_gap_days
                duty_hours = p.duty_hours_per_week
                sleep = max(4.0, 7.5 - (night_shifts * 0.12))

                feature_dict = {
                    'Age': p.age,
                    'Gender': p.gender,
                    'Marital_Status': 'Married' if p.age >= 26 else 'Single',
                    'Location': p.location,
                    'Job_Role': p.job_role,
                    'Experience_Years': p.experience_years,
                    'Monthly_Salary_INR': 45000.0 + (p.experience_years * 3200.0),
                    'Company_Size': 'Large',
                    'Department': p.department if p.department in ['Engineering', 'Operations', 'HR', 'Marketing'] else 'Operations',
                    'Working_Hours_per_Week': duty_hours,
                    'Duty_Hours_Per_Week': duty_hours,
                    'Commute_Time_Hours': 0.5,
                    'Remote_Work': 'No',
                    'Annual_Leaves_Taken': max(0, min(30, int(p.experience_years * 2))),
                    'Team_Size': 30,
                    'Health_Issues': '',
                    'Sleep_Hours': sleep,
                    'Physical_Activity_Hours_per_Week': 5.0,
                    'Mental_Health_Leave_Taken': 'No',
                    'Burnout_Symptoms': 'Often' if (consec_days > 14 or leave_gap > 180) else ('Sometimes' if consec_days > 7 else 'Rarely'),
                    'BusinessTravel': 'Travel_Rarely',
                    'DistanceFromHome': 15.0,
                    'JobLevel': min(5, max(1, int(p.experience_years / 5) + 1)),
                    'JobSatisfaction': 3,
                    'NumCompaniesWorked': 1,
                    'OverTime': 'Yes' if duty_hours > 50 else 'No',
                    'PerformanceRating': 3,
                    'RelationshipSatisfaction': 3,
                    'TrainingTimesLastYear': p.training_load,
                    'WorkLifeBalance': 2 if duty_hours > 55 else 3,
                    'YearsAtCompany': p.experience_years,
                    'YearsInCurrentRole': min(p.experience_years, 3.0),
                    'YearsSinceLastPromotion': 2.0,
                    'YearsWithCurrManager': 2.0,
                    'Deployment_Days': p.deployment_days,
                    'Night_Shifts_Per_Month': night_shifts,
                    'Consecutive_Duty_Days': consec_days,
                    'Transfer_Frequency': p.transfer_frequency,
                    'Training_Load': p.training_load,
                    'Leave_Gap_Days': leave_gap,
                    'Remote_Posting': p.remote_posting,
                    'Operational_Exposure': p.operational_exposure
                }

                result = service.predictor.assess_personnel(feature_dict)
                probas = result["probabilities"]

                # Stagger assessment timestamps slightly over the past week for realism
                timestamp = datetime.now(timezone.utc) - timedelta(days=(i % 7), hours=(i * 2))

                assessment = StressAssessment(
                    personnel_id=p.id,
                    stress_level=result["stress_level"],
                    low_probability=probas.get("Low", 0.0),
                    medium_probability=probas.get("Medium", 0.0),
                    high_probability=probas.get("High", 0.0),
                    risk_score=result["risk_score"],
                    risk_priority=result["risk_priority"],
                    key_factors=json.dumps(result["key_factors"]),
                    model_version="1.0.0-LightGBM",
                    assessment_timestamp=timestamp
                )
                db.add(assessment)
                db.flush()

                # Save recommendations
                status_choices = ["pending", "acknowledged", "completed"]
                for j, rec in enumerate(result.get("recommendations", [])):
                    assigned_status = status_choices[(i + j) % 3] if i > 3 else "pending"
                    if isinstance(rec, dict):
                        rec_type = rec.get("type", "General Welfare")
                        rec_text = rec.get("action", "")
                        rec_priority = rec.get("priority", result["risk_priority"])
                    else:
                        rec_text = str(rec)
                        rec_lower = rec_text.lower()
                        if any(k in rec_lower for k in ["workload", "duty", "hours", "pacing"]):
                            rec_type = "Workload Optimization"
                        elif any(k in rec_lower for k in ["sleep", "rest", "circadian"]):
                            rec_type = "Sleep & Recovery"
                        elif any(k in rec_lower for k in ["leave", "block", "sanctioned"]):
                            rec_type = "Restorative Leave"
                        elif any(k in rec_lower for k in ["medical", "clinical", "health"]):
                            rec_type = "Medical Consultation"
                        elif any(k in rec_lower for k in ["interview", "counselor", "peer-support", "welfare"]):
                            rec_type = "Welfare Support"
                        else:
                            rec_type = "Operational Adjustment"
                        rec_priority = result["risk_priority"]

                    welfare_rec = WelfareRecommendation(
                        personnel_id=p.id,
                        assessment_id=assessment.id,
                        recommendation_type=rec_type,
                        recommendation_text=rec_text,
                        priority=rec_priority,
                        status=assigned_status,
                        created_at=timestamp
                    )
                    db.add(welfare_rec)

        # Ensure standard demo users exist for testing & UI access
        demo_users = [
            ("admin", "AdminPassword123!", "admin", None, None, None),
            ("officer_sharma", "OfficerPassword123!", "officer", None, "1st Battalion", "Srinagar"),
            ("jawan_verma", "PersonnelPassword123!", "personnel", 1, "1st Battalion", "Srinagar")
        ]
        for uname, pwd, role, p_id, bat, loc in demo_users:
            existing = db.query(User).filter(User.username == uname).first()
            if not existing:
                db.add(User(
                    username=uname,
                    hashed_password=hash_password(pwd),
                    role=role,
                    personnel_id=p_id,
                    battalion=bat,
                    location=loc,
                    is_active=True
                ))
            else:
                existing.hashed_password = hash_password(pwd)

        db.commit()
        logger.info("Successfully completed database seeding with 15 synthetic personnel, test users, and ML assessments.")

    except Exception as e:
        db.rollback()
        logger.error(f"Seeding failed: {str(e)}", exc_info=True)
        raise e
    finally:
        db.close()

if __name__ == "__main__":
    seed_database()
